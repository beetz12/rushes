import test from 'node:test';
import assert from 'node:assert/strict';
import * as failureEvidenceFiles from 'node:fs/promises';
import * as failureEvidencePaths from 'node:path';
import * as failureEvidenceSystem from 'node:os';
import * as failureEvidenceDigests from 'node:crypto';
import { retainGeneratedCapture } from './generated-capture-evidence.mjs';
const source = await failureEvidenceFiles.readFile(new URL('./capture.test.mjs', import.meta.url), 'utf8');
const begin = source.indexOf('      // Terminal generated failure retention;');
const end = source.indexOf('\n      throw error;', begin) + '\n      throw error;'.length;
assert.ok(begin > 0 && end > begin);
const collect = new (Object.getPrototypeOf(async function() {}).constructor)(
  'take', 'snapshot', 'error', 'testExpiresAt', 'window', source.slice(begin, end));

test('known permanently short failure retains all opaque generated originals without becoming complete', async () => {
  const root = await failureEvidenceFiles.mkdtemp(failureEvidencePaths.join(failureEvidenceSystem.tmpdir(), 'rushes-failure-evidence-'));
  try {
    const kinds = ['screen', 'camera', 'microphone', 'tab-audio', 'composed'];
    const original = new Error('Known permanent short extent'), reads = [];
    const snapshot = { manifest: { state: 'interrupted', durationMs: 1240, recoveryNote: 'Known short980ms extent' } };
    const bytes = Object.fromEntries(kinds.map(kind => [kind, Buffer.from(`generated opaque bytes:${kind}`)]));
    const take = { id: 'generated-only', store: { async trackBlob(id, kind) {
      assert.equal(id, 'generated-only'); reads.push(kind); return new Blob([bytes[kind]]);
    } } };
    await assert.rejects(collect(take, snapshot, original, Date.now() + 45000,
      { witnessStage: async value => retainGeneratedCapture(root, 'witness-stop-failure', value) }), error => error === original);
    assert.deepEqual(reads, kinds);
    const saved = JSON.parse(await failureEvidenceFiles.readFile(failureEvidencePaths.join(root, 'witness-stop-failure.log'), 'utf8'));
    assert.equal(saved.snapshot.manifest.state, 'interrupted'); assert.equal(saved.originalError, String(original));
    assert.equal(saved.sourcePCM.availability, 'missing');
    for (const kind of kinds) {
      const actual = await failureEvidenceFiles.readFile(failureEvidencePaths.join(root, saved.files[kind].name));
      assert.deepEqual(actual, bytes[kind]);
      assert.equal(saved.files[kind].sha256, failureEvidenceDigests.createHash('sha256').update(actual).digest('hex'));
    }
  } finally { await failureEvidenceFiles.rm(root, { recursive: true }); }
});
test('nonterminal failure never reads tracks and preserves the actual original error', async () => {
  const original = new Error('Original nonterminal failure'); let reads = 0;
  await assert.rejects(collect({ store: { trackBlob() { reads++; } } }, { manifest: { state: 'stopping' } },
    original, Date.now() + 45000, {}), error => error === original);
  assert.equal(reads, 0);
});
test('evidence transport failure cannot mask the original permanent-short error', async () => {
  const original = new Error('Original permanent-short failure');
  await assert.rejects(collect({ id: 'generated', store: { async trackBlob() { return new Blob(['opaque generated bytes']); } } },
    { manifest: { state: 'interrupted' } }, original, Date.now() + 45000,
    { witnessStage: async () => { throw new Error('Generated evidence transport refusal'); } }), error => error === original);
});
test('already-aborted evidence IO refuses before creating the owned destination', async () => {
  const root = await failureEvidenceFiles.mkdtemp(failureEvidencePaths.join(failureEvidenceSystem.tmpdir(), 'rushes-canceled-evidence-'));
  try {
    const target = failureEvidencePaths.join(root, 'not-created'), cancel = new AbortController(); cancel.abort();
    await assert.rejects(retainGeneratedCapture(target, 'witness-stop-failure', { retained: {} }, { signal: cancel.signal }), error => error.name === 'AbortError');
    await assert.rejects(failureEvidenceFiles.stat(target), error => error.code === 'ENOENT');
  } finally { await failureEvidenceFiles.rm(root, { recursive: true }); }
});

const catchBegin = source.indexOf('      // Preserve the original failure when its snapshot observation refuses.');
const catchEnd = source.indexOf('    } finally { release?.(); }', catchBegin);
assert.ok(catchBegin > 0 && catchEnd > catchBegin);
const actualCatch = new (Object.getPrototypeOf(async function() {}).constructor)(
  'take', 'error', 'testExpiresAt', 'window', source.slice(catchBegin, catchEnd));
for (const transportRefuses of [false, true]) test('snapshot refusal cannot mask original error; transportRefuses=' + transportRefuses, async () => {
  const original = new Error('Actual permanent-short failure'), observations = []; let reads = 0;
  const take = { snapshot() { throw new Error('Generated snapshot refusal'); },
    store: { trackBlob() { reads++; throw new Error('No terminal snapshot permits reads'); } } };
  await assert.rejects(actualCatch(take, original, Date.now() + 45000, { witnessStage: async value => {
    observations.push(value); if (transportRefuses) throw new Error('Generated reporting refusal');
  } }), error => error === original);
  assert.equal(reads, 0); assert.equal(observations[0].error, String(original));
  assert.equal(observations[0].snapshot, null); assert.equal(observations[0].snapshotAvailability, 'unavailable');
});
