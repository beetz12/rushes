import { test, expect } from 'vitest';
import * as releaseFixtures from 'node:fs/promises';
import * as releaseLocations from 'node:path';
import * as releaseTemporary from 'node:os';
import * as releaseHashes from 'node:crypto';
import { distributionPlan, writePackagedUpdatePolicy, collectDistribution } from '../scripts/distribution.mjs';
import { publicReleaseURL, validateRelease, validateUpdatePolicy, releaseArtifact, ARTIFACT_BYTES } from '../scripts/release-policy.mjs';

const version = '1.2.3';
const digest = releaseHashes.createHash('sha512').update('generated bytes').digest('base64');
function manifest() {
  return { schema: 'rushes.mac-release/1', appId: 'com.nexai.rushes', platform: 'darwin', arch: 'arm64',
    version, releaseDate: '2026-10-24T00:00:00.000Z', files: ['zip', 'dmg'].map(extension => ({ url: releaseArtifact(version, extension), size: 15, sha512: digest })) };
}
async function folder(t) {
  const directory = await releaseFixtures.mkdtemp(releaseLocations.join(releaseTemporary.tmpdir(), 'rushes-release-fixture-'));
  t.onTestFinished(() => releaseFixtures.rm(directory, { recursive: true, force: true })); return directory;
}
test('public release directories reject secrets, local addresses and alternate protocols', () => {
  expect(publicReleaseURL('https://downloads.example.org/rushes')).toBe('https://downloads.example.org/rushes/');
  for (const input of ['http://downloads.example.org/', 'https://user:secret@downloads.example.org/',
    'https://localhost/', 'https://localhost./', 'https://host.localdomain/', 'https://127.0.0.1/', 'https://[::1]/', 'https://private.local/',
    'https://host.invalid/', 'https://downloads.example.org/?token=private', 'https://downloads.example.org/#part',
    'https://downloads.example.org:444/', 'file:///tmp/update', undefined]) expect(() => publicReleaseURL(input)).toThrow();
});
test('fixed release identity and checksum schema refuses malformed or redirected assets', () => {
  expect(validateRelease(manifest()).files).toHaveLength(2);
  for (const version of ['01.2.3', '1.2', '1.2.3.4', '1.2.-1', '1.2.9007199254740992']) {
    const value = manifest(); value.version = version; expect(() => validateRelease(value)).toThrow();
  }
  for (const change of [m => { m.arch = 'x64'; }, m => { m.ownerToken = 'not-a-release-field'; },
    m => { m.version = '1.2.3-beta'; }, m => { m.releaseDate = 'yesterday'; },
    m => { m.files[0].url = 'https://foreign.example.org/update.zip'; },
    m => { m.files[0].url = '../update.zip'; }, m => { m.files[1] = m.files[0]; },
    m => { m.files.pop(); }, m => { m.files[0].size = 0; }, m => { m.files[0].size = ARTIFACT_BYTES + 1; },
    m => { m.files[0].size = NaN; }, m => { m.files[0].sha512 = 'not-a-digest'; }]) {
    const value = manifest(); change(value); expect(() => validateRelease(value)).toThrow();
  }
});
test('development policy cannot acquire an enabled feed from incidental environment', () => {
  const plan = distributionPlan({ RUSHES_SIGN_TYPE: 'development', RUSHES_SIGN_IDENTITY: '-',
    RUSHES_UPDATE_URL: 'https://downloads.example.org/' }, version);
  expect(plan.policy).toEqual({ schema: 'rushes.mac-updates/1', enabled: false }); expect(plan.config.publish).toEqual([]);
  expect(() => validateUpdatePolicy({ ...plan.policy, feedURL: 'https://downloads.example.org/' })).toThrow();
  expect(() => distributionPlan({ RUSHES_SIGN_TYPE: 'development', RUSHES_SIGN_IDENTITY: 'unknown' }, version)).toThrow();
});
test('the before-sign update policy is version-bound, exclusive and cancelled before mutation', async t => {
  const directory = await folder(t), resources = releaseLocations.join(directory, 'Rushes.app/Contents/Resources');
  await releaseFixtures.mkdir(resources, { recursive: true });
  const context = { appOutDir: directory, packager: { appInfo: { version }, info: { cancellationToken: { cancelled: false } } } };
  const plan = distributionPlan({ RUSHES_SIGN_TYPE: 'development', RUSHES_SIGN_IDENTITY: '-' }, version);
  context.packager.info.cancellationToken.cancelled = true;
  await expect(writePackagedUpdatePolicy(context, plan)).rejects.toThrow(/cancelled/);
  await expect(releaseFixtures.access(releaseLocations.join(resources, 'RushesUpdates.json'))).rejects.toThrow();
  context.packager.info.cancellationToken.cancelled = false; context.packager.appInfo.version = '1.2.4';
  await expect(writePackagedUpdatePolicy(context, plan)).rejects.toThrow(/version/); context.packager.appInfo.version = version;
  await writePackagedUpdatePolicy(context, plan);
  expect(JSON.parse(await releaseFixtures.readFile(releaseLocations.join(resources, 'RushesUpdates.json'), 'utf8'))).toEqual(plan.policy);
  await expect(writePackagedUpdatePolicy(context, plan)).rejects.toMatchObject({ code: 'EEXIST' });
});
test('artifact receipt hashes actual unsigned fixture bytes without inventing a signing verdict', async t => {
  const directory = await folder(t), artifacts = [];
  for (const extension of ['zip', 'dmg']) {
    const file = releaseLocations.join(directory, releaseArtifact(version, extension));
    await releaseFixtures.writeFile(file, 'UNSIGNED GENERATED BYTE FIXTURE. Not an installer or signature.'); artifacts.push(file);
  }
  const result = await collectDistribution(artifacts, { version, production: true });
  const saved = JSON.parse(await releaseFixtures.readFile(result.manifestPath, 'utf8'));
  expect(validateRelease(saved).files).toHaveLength(2); expect(result.published).toBe(false);
  expect(saved).not.toHaveProperty('signed'); expect(saved).not.toHaveProperty('notarized');
  for (const item of saved.files) {
    const bytes = await releaseFixtures.readFile(releaseLocations.join(directory, item.url));
    expect(item.size).toBe(bytes.length); expect(item.sha512).toBe(releaseHashes.createHash('sha512').update(bytes).digest('base64'));
  }
  const development = await collectDistribution(artifacts, { version, production: false });
  expect(JSON.parse(await releaseFixtures.readFile(development.manifestPath, 'utf8')).updatesEnabled).toBe(false);
});
test('missing, duplicate, linked, empty and oversized artifacts refuse manifest creation', async t => {
  const directory = await folder(t), files = ['zip', 'dmg'].map(extension => releaseLocations.join(directory, releaseArtifact(version, extension)));
  const plan = { version, production: true };
  await expect(collectDistribution([], plan)).rejects.toThrow(/exactly one/);
  for (const file of files) await releaseFixtures.writeFile(file, 'unsigned fixture');
  await expect(collectDistribution([...files, files[0]], plan)).rejects.toThrow(/exactly one/);
  const target = releaseLocations.join(directory, 'linked-fixture'); await releaseFixtures.writeFile(target, 'unsigned fixture');
  await releaseFixtures.rm(files[0]); await releaseFixtures.symlink(target, files[0]);
  await expect(collectDistribution(files, plan)).rejects.toThrow(/linked/);
  await releaseFixtures.rm(files[0]); await releaseFixtures.writeFile(files[0], '');
  await expect(collectDistribution(files, plan)).rejects.toThrow(/size bound/);
  const handle = await releaseFixtures.open(files[0], 'r+'); try { await handle.truncate(ARTIFACT_BYTES + 1); } finally { await handle.close(); }
  await expect(collectDistribution(files, plan)).rejects.toThrow(/size bound/);
});
