function release() {
  const hash = updateDigests.createHash('sha512').update('generated bytes').digest('base64');
  return validateRelease({ schema: 'rushes.mac-release/1', appId: 'com.nexai.rushes', platform: 'darwin', arch: 'arm64',
    version: '0.1.2', releaseDate: '2026-10-24T00:00:00.000Z', files: ['zip', 'dmg'].map(extension => ({
      url: `Rushes-0.1.2-arm64.${extension}`, size: 15, sha512: hash })) });
}
class UpdateReply<T> {
  readonly promise: Promise<T>;
  private settleUpdate!: (payload: T) => void;
  constructor() { this.promise = new Promise<T>(updateReply => { this.settleUpdate = updateReply; }); }
  resolve(payload: T) { this.settleUpdate(payload); }
}
function driver() {
  let listener: Parameters<UpdateDriver['listen']>[0] | undefined;
  const result = { version: '0.1.2', bytes: 15 };
  const port: UpdateDriver = {
    check: vi.fn(async () => result), download: vi.fn(async () => undefined), cancel: vi.fn(), install: vi.fn(),
    listen: vi.fn(value => { listener = value; return () => { listener = undefined; }; }),
  };
  return { port, result, emit: (event: Parameters<NonNullable<typeof listener>>[0]) => listener?.(event) };
}

test('bounded public feed reads one JSON manifest without redirects or credentials', async () => {
  let signal: AbortSignal | undefined;
  const fetcher: typeof fetch = async (input, init) => {
    expect(String(input)).toBe('https://downloads.example.org/rushes/latest-mac.json');
    expect(init?.redirect).toBe('error'); expect(init?.credentials).toBe('omit');
    signal = init?.signal ?? undefined;
    return new Response(JSON.stringify(release()), { headers: { 'content-type': 'application/json' } });
  };
  expect((await fetchMacRelease('https://downloads.example.org/rushes/', fetcher)).version).toBe('0.1.2');
  expect(signal?.aborted).toBe(true);
});
test('oversized, non-JSON and redirected feeds refuse before download decisions', async () => {
  for (const response of [new Response('{}', { status: 302, headers: { location: 'https://foreign.example.org/' } }),
    new Response('<html>error</html>', { headers: { 'content-type': 'text/html' } }),
    new Response('{}', { headers: { 'content-type': 'application/json', 'content-length': '65537' } }),
    new Response(' '.repeat(65537), { headers: { 'content-type': 'application/json' } })]) {
    await expect(fetchMacRelease('https://downloads.example.org/', async () => response)).rejects.toThrow();
  }
});
