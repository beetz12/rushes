test('capture activity suppresses check/download and cancels late check results', async () => {
  let busy = true; const f = driver(), pending = new UpdateReply<typeof f.result | null>();
  const updates = new ReleaseUpdates(f.port, { isBusy: () => busy });
  expect((await updates.check()).deferred).toBe(true); expect(f.port.check).not.toHaveBeenCalled();
  busy = false; vi.mocked(f.port.check).mockReturnValueOnce(pending.promise); const checking = updates.check();
  busy = true; updates.activityChanged(); pending.resolve(f.result); await checking;
  expect(f.port.cancel).toHaveBeenCalled(); expect(f.port.download).not.toHaveBeenCalled(); expect(updates.snapshot().deferred).toBe(true);
});
test('a take beginning during download prevents a late readiness or automatic restart', async () => {
  let busy = false; const f = driver(), held = new UpdateReply<void>(); vi.mocked(f.port.download).mockReturnValueOnce(held.promise);
  const updates = new ReleaseUpdates(f.port, { isBusy: () => busy }); const checking = updates.check();
  await vi.waitFor(() => expect(f.port.download).toHaveBeenCalled());
  busy = true; updates.activityChanged(); held.resolve(); await checking; updates.restart();
  expect(updates.snapshot().status).toBe('idle'); expect(f.port.install).not.toHaveBeenCalled(); expect(updates.blocksCapture).toBe(false);
});
test('restart is explicit, idle checked, and the committed native latch survives errors', async () => {
  let busy = false; const f = driver(); const updates = new ReleaseUpdates(f.port, { isBusy: () => busy });
  await updates.check(); expect(updates.snapshot().status).toBe('downloaded'); expect(f.port.install).not.toHaveBeenCalled();
  busy = true; updates.restart(); expect(f.port.install).not.toHaveBeenCalled();
  busy = false; updates.restart(); expect(f.port.install).toHaveBeenCalledTimes(1); expect(updates.blocksCapture).toBe(true);
  f.emit({ kind: 'error' }); expect(updates.snapshot()).toMatchObject({ status: 'restarting', reason: 'failed' });
  updates.close(); expect(updates.blocksCapture).toBe(true); updates.restart(); expect(f.port.install).toHaveBeenCalledTimes(1);
});
