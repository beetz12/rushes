test('production adapter keeps upstream checksum/signature handling manual and validates cached length', async t => {
  const directory = await updateFixtures.mkdtemp(updateLocations.join(updateTemporary.tmpdir(), 'rushes-updater-fixture-'));
  t.onTestFinished(() => updateFixtures.rm(directory, { recursive: true, force: true }));
  await updateFixtures.writeFile(updateLocations.join(directory, 'RushesUpdates.json'), JSON.stringify({
    schema: 'rushes.mac-updates/1', enabled: true, feedURL: 'https://downloads.example.org/' }));
  sdkFixture.downloadPath = updateLocations.join(directory, 'unsigned-byte-fixture');
  await updateFixtures.writeFile(sdkFixture.downloadPath, 'generated bytes');
  vi.stubGlobal('fetch', async () => new Response(JSON.stringify(release()), { headers: { 'content-type': 'application/json' } }));
  const observed: UpdateSnapshot[] = [];
  const updates = await createAppUpdater({ packaged: true, resourcesPath: directory, isBusy: () => false, changed: value => observed.push(value) });
  const actual = sdkFixture.instances.at(-1) as { autoDownload: boolean; autoInstallOnAppQuit: boolean; allowDowngrade: boolean; allowPrerelease: boolean };
  expect(actual).toMatchObject({ autoDownload: false, autoInstallOnAppQuit: false, allowDowngrade: false, allowPrerelease: false });
  await updates.check(); expect(updates.snapshot().status).toBe('downloaded'); expect(observed.some(value => value.status === 'downloading')).toBe(true);
  updates.close();
  await updateFixtures.writeFile(sdkFixture.downloadPath, 'wrong size');
  const rejected = await createAppUpdater({ packaged: true, resourcesPath: directory, isBusy: () => false });
  await rejected.check(); expect(rejected.snapshot().status).toBe('error'); rejected.close();
});
test('unpackaged, disabled and malformed packaged policies never load an enabled updater', async t => {
  const directory = await updateFixtures.mkdtemp(updateLocations.join(updateTemporary.tmpdir(), 'rushes-disabled-updates-'));
  t.onTestFinished(() => updateFixtures.rm(directory, { recursive: true, force: true }));
  const before = sdkFixture.instances.length;
  expect((await createAppUpdater({ packaged: false, resourcesPath: directory, isBusy: () => false })).snapshot().status).toBe('disabled');
  for (const value of [{ schema: 'rushes.mac-updates/1', enabled: false },
    { schema: 'rushes.mac-updates/1', enabled: true, feedURL: 'http://127.0.0.1/' }]) {
    await updateFixtures.writeFile(updateLocations.join(directory, 'RushesUpdates.json'), JSON.stringify(value));
    expect((await createAppUpdater({ packaged: true, resourcesPath: directory, isBusy: () => false })).snapshot().status).toBe('disabled');
  }
  expect(sdkFixture.instances).toHaveLength(before);
});
